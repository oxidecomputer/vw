//! `vw mist init` — a mixed-signal testbench.
//!
//! A mixed-signal bench co-simulates a VHDL entity against a Xyce circuit.
//! Unlike the other two kinds there is no wrapper entity: the design entity
//! *is* the top level, and what the bench adds is a Rust bridge that reads
//! its output ports each cycle, writes them into the circuit's DAC sources,
//! and steps Xyce forward.
//!
//! Almost all of that bridge is derived from `mist.toml` and already
//! generated by [`crate::sim::bridge`] — the FFI wrapper, the C++ shim, the
//! link configuration, the signal handles, the encoders. What was missing was
//! the `mist.toml` itself and a circuit for it to point at, which had to be
//! written by hand before any of the generation would run. That is what this
//! writes.

use camino::Utf8Path;

use super::entity::{DesignTypes, EntityInterface, Interface, Reach};
use super::{write_new_file, Created};
use crate::{MistConfig, PortMapping, Result, VhdlStandard};

/// Default clock for a bench that did not say.
///
/// 100 MHz: fast enough to be a plausible digital clock, slow enough that the
/// generated `.TRAN` step is not absurd. It is one line in `mist.toml` to
/// change, and the analog model usually decides the real answer anyway.
const DEFAULT_CLOCK_HZ: f64 = 100e6;

/// Create a mixed-signal testbench.
///
/// `entity` names the design entity to co-simulate. It is optional the same
/// way `--dut` is elsewhere: without it a `mist.toml` is still written, with
/// the entity and the port map left to fill in.
pub fn init(
    workspace_dir: &Utf8Path,
    name: &str,
    entity: Option<&str>,
    clock_hz: Option<f64>,
    vhdl_std: VhdlStandard,
) -> Result<Created> {
    // Not `base_name`: a mixed-signal bench's name is a directory and a crate
    // name, never a VHDL entity, so `tx-eq` is a perfectly good name for one.
    super::check_crate_name(name)?;

    let dut = entity
        .map(|e| super::entity::load(workspace_dir, e, vhdl_std))
        .transpose()?;
    // A design's analog-facing ports are very often subtypes — `Pam4Symbol`,
    // `EqIndex` — and a subtype says nothing about its own width, so which
    // ports can drive a DAC is a question about the design's types.
    let types = match &dut {
        Some(_) => super::entity::design_types(workspace_dir, vhdl_std)?,
        None => DesignTypes::default(),
    };

    let mut files = super::workspace::ensure_bench_workspace(workspace_dir)?;

    let bench_dir = workspace_dir.join("bench").join(name);
    super::check_available(&bench_dir)?;
    std::fs::create_dir_all(bench_dir.join("analog").as_std_path())?;

    let clock = clock_hz.unwrap_or(DEFAULT_CLOCK_HZ);
    let config = mist_config(name, dut.as_ref(), &types, clock);

    let netlist = bench_dir.join("analog").join("model.cir");
    write_new_file(&netlist, &render_netlist(name, &config, dut.as_ref()))?;
    files.push(netlist);

    let toml = bench_dir.join("mist.toml");
    write_new_file(&toml, &render_mist_toml(&config, dut.as_ref()))?;
    files.push(toml);

    // Everything else a mixed-signal bench needs — the crate manifest, the
    // link configuration, the C++ shim, the generated handles and encoders,
    // and a starting `src/lib.rs` — is derived from the config that was just
    // written, by the same code that keeps it up to date on every run.
    crate::sim::scaffold(&bench_dir, &config)?;
    for generated in [
        "Cargo.toml",
        "build.rs",
        "xyce_cinterface.cpp",
        "src/xyce.rs",
        "src/generated.rs",
        "src/lib.rs",
        ".gitignore",
    ] {
        files.push(bench_dir.join(generated));
    }

    let registered = super::workspace::register_member(workspace_dir, name)?;

    Ok(Created {
        name: name.to_string(),
        files,
        registered,
        next_steps: next_steps(name, dut.as_ref()),
    })
}

fn next_steps(name: &str, dut: Option<&EntityInterface>) -> Vec<String> {
    let mut steps = vec![format!(
        "write the circuit in `bench/{name}/analog/model.cir` — it has a DAC \
         per mapped port and a placeholder output stage"
    )];
    match dut {
        Some(dut) => steps.push(format!(
            "check the `[ports]` map in `bench/{name}/mist.toml`: every one \
             of {}'s outputs is mapped as `unsigned`, and a PAM4 symbol port \
             wants `encoding = \"pam4\"` instead",
            dut.name,
        )),
        None => steps.push(format!(
            "set `entity` and `[ports]` in `bench/{name}/mist.toml`, or \
             re-run with `--entity <name>` to have them filled in"
        )),
    }
    steps.push(format!(
        "drive the test from `bench/{name}/src/lib.rs`, then run it with \
         `vw bench run {name}`"
    ));
    steps
}

/// The `mist.toml` a new bench starts from.
fn mist_config(
    name: &str,
    dut: Option<&EntityInterface>,
    types: &DesignTypes,
    clock: f64,
) -> MistConfig {
    MistConfig {
        netlist: "analog/model.cir".to_string(),
        entity: dut
            .map(|d| d.name.clone())
            // A placeholder rather than a blank: `vw bench run` reports a
            // missing entity by name, which reads as an instruction.
            .unwrap_or_else(|| format!("TODO_{name}_entity")),
        clock,
        prime_cycles: Some(0),
        ports: dac_ports(dut, types),
    }
}

/// One DAC per output port the bridge can encode.
///
/// Outputs only: the mapping exists so the bridge can read a VHDL port each
/// cycle and drive the corresponding analog source with it. An input port has
/// nothing to read.
fn dac_ports(
    dut: Option<&EntityInterface>,
    types: &DesignTypes,
) -> std::collections::HashMap<String, PortMapping> {
    let Some(dut) = dut else {
        return std::collections::HashMap::new();
    };
    dut.outputs()
        // The bridge reads a port as a bit string and encodes it, so only a
        // port that *is* one can drive a DAC. Resolved through the design's
        // subtype declarations, since `Pam4Symbol` is a bit string and
        // nothing about the name says so.
        .filter(|p| types.reach(&p.subtype) == Reach::Bits)
        .map(|p| {
            (
                p.name.clone(),
                PortMapping {
                    dac: format!("dac_{}", p.name),
                    // Every port starts as a plain unsigned value. PAM4 is a
                    // property of what the port *means*, which the type does
                    // not say, so it is flagged in the file rather than
                    // guessed at here.
                    encoding: "unsigned".to_string(),
                },
            )
        })
        .collect()
}

/// `mist.toml`, written by hand rather than serialized.
///
/// The generated file is the one a developer edits first and most, so it is
/// worth its comments — and a serializer would drop them and reorder the port
/// map into whatever the hash map felt like.
fn render_mist_toml(
    config: &MistConfig,
    dut: Option<&EntityInterface>,
) -> String {
    let mut out = String::from(
        "# Mixed-signal testbench configuration.\n\
         #\n\
         # Everything under `bench/<name>/` except this file, the circuit and\n\
         # `src/lib.rs` is generated from here and rewritten on every run.\n\
         \n",
    );

    out.push_str(&format!(
        "# The Xyce circuit, relative to this file.\n\
         netlist = \"{}\"\n\n",
        config.netlist,
    ));

    if dut.is_some() {
        out.push_str(
            "# The VHDL entity to co-simulate. It is the top level:\n\
                      # there is no wrapper, and nvc elaborates it directly.\n",
        );
    } else {
        out.push_str(
            "# TODO: the VHDL entity to co-simulate. It is the top level:\n\
             # there is no wrapper, and nvc elaborates it directly.\n",
        );
    }
    out.push_str(&format!("entity = \"{}\"\n\n", config.entity));

    out.push_str(&format!(
        "# Clock frequency in Hz. The bridge advances Xyce by one period per\n\
         # rising edge of the entity's clock.\n\
         clock = {}\n\n\
         # Cycles to run before the test's own logic starts, for a design \
         whose\n\
         # pipeline has to fill first.\n\
         prime-cycles = {}\n\n",
        format_hz(config.clock),
        config.prime_cycles.unwrap_or(0),
    ));

    out.push_str(
        "# Which entity output drives which analog source, and how its bits \
         are\n\
         # read. `unsigned` treats the port as a plain binary number; `pam4` \
         maps\n\
         # a two-bit symbol onto the levels 0.0 to 3.0.\n\
         #\n\
         # Each `dac` here must name a YDAC device in the circuit.\n\
         [ports]\n",
    );

    if config.ports.is_empty() {
        out.push_str(
            "# TODO: one entry per output the circuit is driven by, e.g.\n\
             # \"data_out\" = { dac = \"dac_data_out\", encoding = \
             \"unsigned\" }\n",
        );
        return out;
    }

    let mut names: Vec<&String> = config.ports.keys().collect();
    names.sort();
    let width = names.iter().map(|n| n.len() + 2).max().unwrap_or(0);
    for name in names {
        let mapping = &config.ports[name];
        let quoted = format!("\"{name}\"");
        out.push_str(&format!(
            "{quoted:width$} = {{ dac = \"{}\", encoding = \"{}\" }}\n",
            mapping.dac, mapping.encoding,
        ));
    }
    out
}

/// A time in seconds, at the precision a netlist wants.
///
/// Xyce reads full precision perfectly well, but a person editing the file
/// does not need to be told the DAC's rise time to seventeen digits — and
/// these are starting points to be adjusted, not values to be preserved.
fn seconds(t: f64) -> String {
    format!("{t:.4e}")
}

/// Render a frequency the way a person would write it, so the file reads as
/// `26.5625e9` rather than `26562500000`.
fn format_hz(hz: f64) -> String {
    let text = format!("{hz:e}");
    // `{:e}` gives `1e8`; TOML wants a fractional part to read as a float and
    // `serde` wants one to parse it back as one.
    match text.split_once('e') {
        Some((mantissa, exponent)) if !mantissa.contains('.') => {
            format!("{mantissa}.0e{exponent}")
        }
        _ => text,
    }
}

/// A circuit that is valid, runnable, and obviously a placeholder.
///
/// It has to actually solve: the bench builds and runs the moment it is
/// created, and a netlist that Xyce rejects would turn the first run into a
/// debugging session about SPICE syntax rather than a working starting point.
/// So every DAC gets a load, and there is a differential output pair carrying
/// the first mapped port — which is what the generated `src/lib.rs` reads.
fn render_netlist(
    name: &str,
    config: &MistConfig,
    dut: Option<&EntityInterface>,
) -> String {
    let mut out = format!(
        "{name} mixed-signal model\n\
         *\n\
         * Scaffolded by `vw mist init`. Every DAC below is written each \
         cycle by\n\
         * the Rust bridge from the VHDL port `mist.toml` maps to it.\n\
         *\n\
         * TODO: replace the output stage at the bottom with the circuit \
         under\n\
         * test. What is there now only makes the netlist solvable so the \
         bench\n\
         * runs from the moment it is created.\n\
         *\n\
         \n\
         * ==========================================================================\n\
         * Digital-to-analog inputs\n\
         * ==========================================================================\n\
         *\n\
         * `YDAC <device> <node> 0 <model>` — the bridge drives <device>, the\n\
         * circuit reads V(<node>).\n\
         *\n",
    );

    let mut names: Vec<&String> = config.ports.keys().collect();
    names.sort();

    if names.is_empty() {
        out.push_str(
            "* TODO: one YDAC per port, once mist.toml maps some.\n\
             YDAC dac_placeholder placeholder 0 dacmodel\n\
             Rplaceholder placeholder 0 1meg\n\n",
        );
    } else {
        for name in &names {
            let mapping = &config.ports[name.as_str()];
            let subtype = dut
                .and_then(|d| d.ports.iter().find(|p| &&p.name == name))
                .map(|p: &Interface| p.subtype.clone())
                .unwrap_or_default();
            if subtype.is_empty() {
                out.push_str(&format!("* {name}\n"));
            } else {
                out.push_str(&format!("* {name} : {subtype}\n"));
            }
            out.push_str(&format!("YDAC {} {name} 0 dacmodel\n", mapping.dac,));
            // A DAC with nothing attached leaves its node in a subcircuit
            // Xyce has no equation for. A large resistor to ground is inert
            // and keeps the matrix solvable until there is a real circuit.
            out.push_str(&format!("R{name} {name} 0 1meg\n\n"));
        }

        out.push_str(&format!(
            "* Rise and fall times a hundredth of the {} clock period, so a \n\
             * transition is well inside the cycle that produced it.\n",
            seconds(1.0 / config.clock),
        ));
    }

    out.push_str(&format!(
        "\n.model dacmodel DAC (tr={0} tf={0})\n\n",
        seconds((0.01 / config.clock).max(1e-15)),
    ));

    out.push_str(
        "* ==========================================================================\n\
         * Output stage — PLACEHOLDER\n\
         * ==========================================================================\n\
         *\n\
         * A differential pair the generated `src/lib.rs` prints each cycle, \
         so a\n\
         * fresh bench shows something moving. Replace it with the real \
         circuit.\n\
         *\n",
    );

    let source = names
        .first()
        .map(|n| format!("V({n})"))
        .unwrap_or_else(|| "V(placeholder)".to_string());
    out.push_str(&format!(
        "Bout_p 0 out_p I={{{source} / 50}}\n\
         Bout_n 0 out_n I={{-1 * {source} / 50}}\n\
         Rout_p out_p 0 50\n\
         Rout_n out_n 0 50\n\n",
    ));

    // The bridge steps Xyce with `simulate_until`, so the stop time only has
    // to outlast the run; the step is what decides resolution.
    let period = 1.0 / config.clock;
    out.push_str(&format!(
        "* ==========================================================================\n\
         * Analysis\n\
         * ==========================================================================\n\
         *\n\
         * The bridge drives time forward one clock period at a time, so the \
         stop\n\
         * time here only has to outlast the run. UIC starts from initial\n\
         * conditions rather than solving a DC operating point first.\n\
         .TRAN {} {} UIC\n\
         \n\
         * Plots written to `target/bench/{name}/` after the run.\n\
         * @plot timeseries V(out_p) V(out_n) label=\"output\"\n\
         \n\
         .PRINT TRAN V(out_p) V(out_n)\n\
         \n\
         .END\n",
        seconds(period / 16.0),
        seconds(period * 100_000.0),
    ));

    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::bench_init::entity::PortMode;

    fn types() -> DesignTypes {
        let mut types = DesignTypes::default();
        types
            .subtypes
            .insert("pam4symbol".into(), "std_logic_vector(1 downto 0)".into());
        types
    }

    fn port(name: &str, mode: PortMode, subtype: &str) -> Interface {
        Interface {
            name: name.to_string(),
            mode: Some(mode),
            subtype: subtype.to_string(),
            default: None,
        }
    }

    fn dut() -> EntityInterface {
        EntityInterface {
            name: "TxEq".to_string(),
            file: std::path::PathBuf::from("hdl/tx-eq.vhdl"),
            context: Vec::new(),
            generics: Vec::new(),
            ports: vec![
                port("clk", PortMode::In, "std_logic"),
                port("raw", PortMode::In, "std_logic_vector(1 downto 0)"),
                port("main_eq", PortMode::Out, "std_logic_vector(1 downto 0)"),
                port(
                    "eq_main_out",
                    PortMode::Out,
                    "std_logic_vector(6 downto 0)",
                ),
            ],
        }
    }

    /// Only outputs that are bit strings get a DAC: the mapping exists so
    /// the bridge can read a port and write the circuit with it.
    #[test]
    fn outputs_become_dacs_and_inputs_do_not() {
        let ports = dac_ports(Some(&dut()), &types());
        assert_eq!(ports["main_eq"].dac, "dac_main_eq");
        assert!(
            ports.contains_key("main_eq"),
            "a subtype of std_logic_vector is still a bit string",
        );
        assert!(ports.contains_key("eq_main_out"));
        assert!(!ports.contains_key("raw"), "an input has nothing to read");
        assert!(!ports.contains_key("clk"));
        assert!(
            !ports.contains_key("cycles"),
            "an integer has no bit string the bridge can encode",
        );
        assert_eq!(ports.len(), 2);
    }

    /// Every DAC named in `mist.toml` has to exist in the circuit, or the
    /// bridge writes to a device Xyce has never heard of.
    #[test]
    fn every_mapped_dac_appears_in_the_netlist() {
        let config = mist_config("txeq", Some(&dut()), &types(), 26.5625e9);
        let netlist = render_netlist("txeq", &config, Some(&dut()));
        for mapping in config.ports.values() {
            assert!(
                netlist.contains(&format!("YDAC {} ", mapping.dac)),
                "{} missing from the netlist",
                mapping.dac,
            );
        }
        assert!(netlist.contains(".model dacmodel DAC"));
        assert!(netlist.contains(".END"));
    }

    /// The generated `src/lib.rs` prints V(OUT_P) and V(OUT_N) each cycle, so
    /// a starter netlist that does not define them shows nothing on the first
    /// run.
    #[test]
    fn the_placeholder_circuit_defines_what_the_template_reads() {
        let config = mist_config("txeq", Some(&dut()), &types(), 26.5625e9);
        let netlist = render_netlist("txeq", &config, Some(&dut()));
        assert!(netlist.contains("Rout_p out_p 0 50"));
        assert!(netlist.contains("Rout_n out_n 0 50"));
    }

    /// The generated config has to survive a round trip, since that is how
    /// every later run reads it.
    #[test]
    fn the_generated_toml_parses_back_to_the_same_config() {
        let config = mist_config("txeq", Some(&dut()), &types(), 26.5625e9);
        let text = render_mist_toml(&config, Some(&dut()));

        let parsed: MistConfig = toml::from_str(&text).expect("valid toml");
        assert_eq!(parsed.entity, "TxEq");
        assert_eq!(parsed.clock, 26.5625e9);
        assert_eq!(parsed.netlist, "analog/model.cir");
        assert_eq!(parsed.ports.len(), config.ports.len());
        assert_eq!(parsed.ports["eq_main_out"].dac, "dac_eq_main_out");
    }

    /// Without an entity the file is still valid TOML that says what is
    /// missing, rather than something that fails to parse.
    #[test]
    fn a_bench_with_no_entity_still_writes_a_readable_config() {
        let config = mist_config(
            "thing",
            None,
            &DesignTypes::default(),
            DEFAULT_CLOCK_HZ,
        );
        let text = render_mist_toml(&config, None);

        let parsed: MistConfig = toml::from_str(&text).expect("valid toml");
        assert!(parsed.entity.starts_with("TODO_"));
        assert!(parsed.ports.is_empty());
        assert!(text.contains("# TODO: the VHDL entity"));
    }
}
