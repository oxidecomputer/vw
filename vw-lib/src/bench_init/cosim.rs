//! `vw cosim init` — a Rust cosim testbench.
//!
//! The design entity is the top level. nvc elaborates it as it stands and
//! loads a `cdylib` beside it; that library reaches the entity's ports over
//! VHPI and drives them, clock included. There is no VHDL harness — a
//! passthrough wrapper would only be a second copy of the port list to keep
//! in step with the design.
//!
//! What that leaves is a crate, a `build.rs` that finds the GPI libraries, a
//! `cosim.toml` saying which entity, and a registration in the bench cargo
//! workspace. All of it is written here.
//!
//! ## Reaching the ports
//!
//! A record port is not a value in itself — reading the aggregate handle is
//! a category error, and the GPI layer crashes rather than saying so — but
//! its elements are. So a record port becomes one handle per element,
//! `bus_in.go` reached as `dut.get_child("bus_in")?.get_child("go")?`, and
//! nested records are followed down.
//!
//! Subtypes need no special handling at all, as long as nothing is assumed
//! about width at generation time: a signal knows its own, so everything the
//! driver writes is sized from `get_range()` rather than from the type it was
//! declared with. That also makes a port whose width comes from a generic
//! work without the generic being mentioned.
//!
//! What is left over is genuinely awkward and is reported rather than
//! guessed at: an `integer`/`natural` port reads back as an empty bit string,
//! and an array-of-composite has no single bit string that means anything.
//! Both get a handle, and a note saying so.
//!
//! ## What is generated and what is yours
//!
//! `src/generated.rs` is rewritten every time — by `vw cosim init` and before
//! every run — and holds everything derived from the design: the handles, the
//! structs, the entry point. `src/lib.rs` holds `test()` and is written once.
//!
//! That split is what lets a bench grow. A design like a full FPGA top level
//! gets a Rust stand-in for one piece of hard IP at a time, and adding the
//! second must not cost the test written against the first. So `init` is
//! re-runnable: it takes what `cosim.toml` already says, adds whatever the
//! command line asked for, and regenerates. A design change can still break
//! the build — a port that went away takes its handle with it — but it breaks
//! visibly, at compile time, rather than by silently not being there.

use camino::{Utf8Path, Utf8PathBuf};
use proc_macro2::{Literal, TokenStream};
use quote::{format_ident, quote};

use super::entity::{DesignTypes, EntityInterface, Instance, Interface, Reach};
use super::{write_file, write_new_file, Created};
use crate::{Result, VhdlStandard, VwError};

/// The link flags every cosim crate needs, and the only thing in one.
///
/// Regenerated rather than checked in: it is identical in every bench, it is
/// derived from where `rust-cosim` put its GPI libraries, and a bench whose
/// copy has gone missing or gone stale fails at link time with an error that
/// says nothing about any of that. `vw bench run` rewrites it for every cosim
/// crate before building, so there is no state to keep in step.
const BUILD_RS: &str = r#"// Auto-generated by vw — safe to regenerate, and regenerated by `vw bench run`.
//
// A cosim testbench is a cdylib the simulator dlopens, so it has to be linked
// against the GPI libraries `rust-cosim` builds. `rust-cosim` declares
// `links = "cocotb"` and publishes their location as `DEP_COCOTB_TARGET_DIR`,
// which cargo hands to its dependents' build scripts — this one.
use std::env;
use std::path::PathBuf;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    let libs_dir = PathBuf::from(env::var("DEP_COCOTB_TARGET_DIR").expect(
        "DEP_COCOTB_TARGET_DIR is not set — rust-cosim must be a dependency \
         of this crate",
    ));

    if !libs_dir.exists() {
        panic!(
            "the cocotb GPI libraries are not at {}.\n\
             Build rust-cosim first, or run this through `vw bench run`.",
            libs_dir.display(),
        );
    }

    let libs_dir = libs_dir.to_str().expect("GPI library path is not UTF-8");

    println!("cargo:rustc-link-arg=-L{libs_dir}");
    println!("cargo:rustc-link-arg=-lgpi");
    println!("cargo:rustc-link-arg=-lcocotbvhpi_nvc");
    println!("cargo:rustc-link-arg=-Wl,-rpath,{libs_dir}");

    // `vhpi_assert` is the simulator's, resolved when nvc dlopens this. A
    // Linux shared library links with it undefined; the macOS linker refuses
    // to unless told that is the intent.
    if env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("macos") {
        println!("cargo:rustc-link-arg=-Wl,-undefined,dynamic_lookup");
    }
}
"#;

/// The first line of a `build.rs` this wrote, and the only thing that makes
/// it safe to rewrite one.
const BUILD_RS_MARKER: &str = "// Auto-generated by vw";

/// What a cosim bench ignores.
const GITIGNORE: &str = "\
# Auto-generated by vw and rewritten before every run — not worth committing.
build.rs
src/generated.rs

/target/
";

/// Create a Rust cosim testbench, or bring an existing one up to date.
///
/// Re-runnable on purpose. `cosim.toml` is the record of what this bench is —
/// which entity, which instances the driver stands in for — and this reads
/// it, folds in whatever the command line added, writes it back and
/// regenerates. What is regenerated is only ever `src/generated.rs`; the
/// test in `src/lib.rs` is written once and then left alone.
#[allow(clippy::too_many_arguments)]
pub fn init(
    workspace_dir: &Utf8Path,
    name: &str,
    dut: Option<&str>,
    components: &[String],
    vhdl_std: VhdlStandard,
) -> Result<Created> {
    // The name is a directory and a crate name, never a VHDL entity — the
    // entity is the design's — so it is as free as a mixed-signal bench's.
    super::check_crate_name(name)?;

    let bench_dir = workspace_dir.join("bench").join(name);
    let config_path = bench_dir.join("cosim.toml");
    let existing = config_path
        .exists()
        .then(|| crate::cosim::read_config(config_path.as_std_path()))
        .transpose()?;

    // A directory that is not a cosim bench is somebody else's; only one this
    // command made is one it may add to.
    if existing.is_none() {
        super::check_available(&bench_dir)?;
    }

    let config = merge_config(name, existing.as_ref(), dut, components)?;
    let updating = existing.is_some();

    let mut files = super::workspace::ensure_bench_workspace(workspace_dir)?;
    std::fs::create_dir_all(bench_dir.join("src").as_std_path())?;

    // Written from the merged config rather than the flags, so what is on
    // disk always says what the bench is.
    let dut_interface = resolve(workspace_dir, &config, vhdl_std)?;
    if write_file(&config_path, &render_config(name, &config, &dut_interface))?
    {
        files.push(config_path);
    }

    if !updating {
        let manifest = bench_dir.join("Cargo.toml");
        write_new_file(&manifest, &render_manifest(name))?;
        files.push(manifest);

        // Written once and then yours. Everything the design decides lives
        // next door in `generated.rs`, so this never has to be rewritten.
        let lib = bench_dir.join("src").join("lib.rs");
        write_new_file(&lib, &render_lib(&config))?;
        files.push(lib);
    }

    files.extend(ensure_generated(&bench_dir, &dut_interface)?);
    files.extend(ensure_scaffold(&bench_dir)?);

    let registered = super::workspace::register_member(workspace_dir, name)?;

    Ok(Created {
        name: name.to_string(),
        files,
        registered,
        updated: updating,
        next_steps: next_steps(
            name,
            &config,
            &dut_interface,
            updating,
            &bench_dir,
        ),
    })
}

/// What the bench is, after the command line has had its say.
fn merge_config(
    name: &str,
    existing: Option<&crate::cosim::CosimConfig>,
    dut: Option<&str>,
    components: &[String],
) -> Result<crate::cosim::CosimConfig> {
    let mut config = existing.cloned().unwrap_or(crate::cosim::CosimConfig {
        // A placeholder rather than a blank: `vw bench run` reports a missing
        // entity by name, which reads as an instruction.
        entity: format!("TODO_{name}_entity"),
        rust_components: Vec::new(),
        generics: Default::default(),
    });

    if let Some(dut) = dut {
        config.entity = dut.to_string();
    }
    // Added rather than replaced: the point of re-running is to grow the
    // list. Taking one back out is a matter of deleting it from the file,
    // which is where the list lives.
    for label in components {
        if !config.rust_components.iter().any(|have| have == label) {
            config.rust_components.push(label.clone());
        }
    }
    config.rust_components.sort();

    if !config.rust_components.is_empty() && config.entity.starts_with("TODO_")
    {
        return Err(VwError::Config {
            message: String::from(
                "--rust-component needs an entity: an instance is found \
                 inside a design, so there has to be one to look in. Pass \
                 --dut, or set `entity` in cosim.toml.",
            ),
        });
    }

    Ok(config)
}

/// The design this bench drives, and the instances it stands in for.
///
/// `None` when the config has no real entity yet — a bench created without
/// `--dut`, which is a valid thing to have and generates a driver that says
/// so.
struct Resolved {
    dut: Option<EntityInterface>,
    components: Vec<Instance>,
    types: DesignTypes,
}

fn resolve(
    workspace_dir: &Utf8Path,
    config: &crate::cosim::CosimConfig,
    vhdl_std: VhdlStandard,
) -> Result<Resolved> {
    if config.entity.starts_with("TODO_") {
        return Ok(Resolved {
            dut: None,
            components: Vec::new(),
            types: DesignTypes::default(),
        });
    }

    let dut = super::entity::load(workspace_dir, &config.entity, vhdl_std)?;
    // Only worth reading the design's type declarations when there is an
    // entity whose ports might use them.
    let types = super::entity::design_types(workspace_dir, vhdl_std)?;
    let components = config
        .rust_components
        .iter()
        .map(|label| {
            super::entity::find_instance(workspace_dir, &dut, label, vhdl_std)
        })
        .collect::<Result<Vec<_>>>()?;

    Ok(Resolved {
        dut: Some(dut),
        components,
        types,
    })
}

/// Write `src/generated.rs`, which is derived from the design and nobody's to
/// edit.
fn ensure_generated(
    bench_dir: &Utf8Path,
    resolved: &Resolved,
) -> Result<Vec<Utf8PathBuf>> {
    let path = bench_dir.join("src").join("generated.rs");
    let contents = render_generated(
        resolved.dut.as_ref(),
        &resolved.components,
        &resolved.types,
    )?;
    Ok(if write_file(&path, &contents)? {
        vec![path]
    } else {
        Vec::new()
    })
}

/// Regenerate `src/generated.rs` for every cosim bench in the workspace.
///
/// Run before the benches build, for the same reason the mixed-signal
/// scaffolding is: the file is a function of the design, and a design that
/// has moved since the last run leaves it describing something that is no
/// longer there. Cheap when nothing changed — the write is content-aware, so
/// cargo does not see a new mtime.
pub fn ensure_all_generated(
    workspace_dir: &Utf8Path,
    vhdl_std: VhdlStandard,
) -> Result<()> {
    for (name, config) in
        crate::cosim::find_cosim_configs(&workspace_dir.join("bench"))?
    {
        let bench_dir = workspace_dir.join("bench").join(&name);
        let resolved = resolve(workspace_dir, &config, vhdl_std)?;
        ensure_generated(&bench_dir, &resolved)?;
    }
    Ok(())
}

fn next_steps(
    name: &str,
    config: &crate::cosim::CosimConfig,
    resolved: &Resolved,
    updating: bool,
    bench_dir: &Utf8Path,
) -> Vec<String> {
    let mut steps = Vec::new();

    // A bench made before the generated half was split out has all of it in
    // `lib.rs`, so the freshly written `generated.rs` sits there unread and
    // nothing said here has any effect. Better to say so than to report
    // success over a file nobody is compiling.
    let lib = bench_dir.join("src").join("lib.rs");
    // `mod generated;` exactly: a bench that includes anodizer's output says
    // `mod generated_structs`, which is a different file and would otherwise
    // pass for this one.
    let wired = std::fs::read_to_string(lib.as_std_path())
        .map(|text| text.contains("mod generated;"))
        .unwrap_or(true);
    if !wired {
        steps.push(format!(
            "`bench/{name}/src/lib.rs` predates the split and holds its own \
             copy of the generated code, so `src/generated.rs` is not being \
             compiled. Cut it down to `mod generated; pub use generated::*;` \
             and your `test()`, and the rest comes from there."
        ));
    }

    let Some(dut) = &resolved.dut else {
        steps.push(format!(
            "name the design entity in `bench/{name}/cosim.toml`, or re-run \
             with `--dut <entity>` to have the handles generated too"
        ));
        steps.push(format!("run it with `vw bench run {name}`"));
        return steps;
    };

    if !updating {
        steps.push(format!(
            "write the checks in `test()` in `bench/{name}/src/lib.rs` — \
             every one of {}'s ports already has a handle on `Tb`",
            dut.name,
        ));
    }

    for component in &resolved.components {
        steps.push(format!(
            "implement {} in `{}` — its outputs are yours to drive and its \
             inputs are what the design sends it",
            component.label,
            struct_name(&component.label),
        ));
    }

    let awkward: Vec<String> =
        plan_handles(dut, Side::Consumer, &resolved.types)
            .into_iter()
            .filter(|h| h.reach != Reach::Bits)
            .map(|h| h.signal)
            .collect();
    if !awkward.is_empty() {
        steps.push(format!(
            "check {}: an integer or composite signal has no bit string a \
             driver can read, so it is left out of `quiesce`",
            awkward.join(", "),
        ));
    }

    if dut.generics.iter().any(|g| g.default.is_none()) {
        steps.push(format!(
            "give the generics in `bench/{name}/cosim.toml` their values — \
             the design declares them without defaults, and with no wrapper \
             there is nowhere else to set them"
        ));
    }

    let _ = config;
    steps.push(format!("run it with `vw bench run {name}`"));
    steps
}

/// Write the files a cosim crate needs but does not own.
fn ensure_scaffold(bench_dir: &Utf8Path) -> Result<Vec<Utf8PathBuf>> {
    let mut written = Vec::new();
    for (path, contents) in [
        (bench_dir.join("build.rs"), BUILD_RS),
        (bench_dir.join(".gitignore"), GITIGNORE),
    ] {
        if write_file(&path, contents)? {
            written.push(path);
        }
    }
    Ok(written)
}

/// Put a cosim crate's `build.rs` back, if it is missing or is a stale copy
/// of one of ours.
///
/// Called for every cosim crate before a run. Two failures it exists to
/// prevent, both of which present as a link error with nothing in it about
/// `build.rs`: a crate created before this existed (or cleaned away by `git
/// clean -fdx`) has none at all, and one written by an older `vw` links
/// against the wrong thing.
///
/// A `build.rs` without the marker is somebody's — a bench that needs an
/// extra link flag, say — and is left exactly as it is. `.gitignore` is never
/// touched here either: a crate may well have one of its own, and repairing
/// a link error is no reason to overwrite it.
pub fn heal(bench_dir: &Utf8Path) -> Result<bool> {
    let path = bench_dir.join("build.rs");
    match std::fs::read_to_string(path.as_std_path()) {
        Ok(existing) if !existing.starts_with(BUILD_RS_MARKER) => Ok(false),
        _ => write_file(&path, BUILD_RS),
    }
}

/// Whether this directory holds a cosim testbench crate.
///
/// The `cdylib` is what makes it one: a crate under `bench/` that is not a
/// `cdylib` is a helper library (shared packet builders, register maps) which
/// is linked into the benches rather than loaded by the simulator, and giving
/// one a GPI-linking `build.rs` would break it. A directory with a
/// `mist.toml` is a mixed-signal bench, whose whole crate — `build.rs`
/// included — is generated from that file instead.
pub fn is_cosim_crate(dir: &Utf8Path) -> bool {
    if dir.join("mist.toml").exists() {
        return false;
    }
    let Ok(text) =
        std::fs::read_to_string(dir.join("Cargo.toml").as_std_path())
    else {
        return false;
    };
    let Ok(manifest) = text.parse::<toml::Value>() else {
        return false;
    };
    manifest.get("package").is_some()
        && manifest
            .get("lib")
            .and_then(|lib| lib.get("crate-type"))
            .and_then(toml::Value::as_array)
            .is_some_and(|kinds| {
                kinds.iter().any(|k| k.as_str() == Some("cdylib"))
            })
}

