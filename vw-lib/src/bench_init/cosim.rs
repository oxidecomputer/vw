    /// The driver *is* the component, so the directions read the other way
    /// round from the design under test: what the entity declares `out` is
    /// driven from here. Backwards, the driver fights the design on every
    /// signal instead of feeding it.
    #[test]
    fn a_components_directions_are_inverted() {
        let text = with_component();

        assert!(text
            .contains("`brq_request_tvalid` — driven from here (std_logic)"));
        assert!(text
            .contains("`lrq_request_tvalid` — sent by the design (std_logic)"));

        // ...and quiescing drives what the driver owns, which is the outputs.
        let component =
            &text[text.find("impl CipsWrapperInst").expect("component impl")..];
        assert!(component.contains("self.drive(&self.brq_request_tdata, 0);"));
        assert!(!component.contains("self.drive(&self.lrq_request_tdata, 0);"));
    }

    /// The signals live in their own struct rather than among the design's,
    /// and are reached through the instance rather than the top level — which
    /// is what lets them be signals that are not ports of anything.
    #[test]
    fn a_component_gets_its_own_struct_reached_through_the_instance() {
        let text = with_component();

        assert!(text.contains("pub struct CipsWrapperInst"));
        assert!(text.contains("pub cips_wrapper_inst: CipsWrapperInst"));
        assert!(
            text.contains("CipsWrapperInst::new(")
                && text.contains(r#"dut.get_child("cips_wrapper_inst")?"#),
            "the struct is built from the instance's own handle",
        );
        assert!(text.contains(
            r#"brq_request_tdata: instance.get_child("brq_request_tdata")?"#
        ));

        // The design's own handles stay on `Tb`, not folded in with them.
        let tb = &text[text.find("pub struct Tb").expect("Tb")
            ..text.find("impl Tb").expect("impl Tb")];
        assert!(tb.contains("pub write_data: SimHandle"));
        assert!(!tb.contains("brq_request_tdata"));
    }

    /// A component is quiesced alongside the design, or its outputs reach the
    /// design as 'U'.
    #[test]
    fn a_component_is_quiesced_at_startup() {
        let text = with_component();
        let quiesce = text.find("tb.quiesce();").expect("tb quiesce");
        let component = text
            .find("tb.cips_wrapper_inst.quiesce();")
            .expect("component");
        let test = text.find("test(&tb).await?;").expect("test");
        assert!(quiesce < component && component < test);
    }

