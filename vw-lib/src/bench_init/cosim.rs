    fn crate_at(kind: &str) -> (tempfile::TempDir, Utf8PathBuf) {
        let guard = tempfile::tempdir().unwrap();
        let dir =
            Utf8PathBuf::from_path_buf(guard.path().to_path_buf()).unwrap();
        std::fs::write(dir.join("Cargo.toml"), kind).unwrap();
        (guard, dir)
    }

    /// A `cdylib` under `bench/` is a testbench. A plain library is shared
    /// helper code the benches link against, and giving one a GPI-linking
    /// `build.rs` would break it.
    #[test]
    fn only_cdylib_crates_count_as_cosim_benches() {
        let (_g, bench) = crate_at(
            "[package]\nname = \"b\"\n[lib]\ncrate-type = [\"cdylib\"]\n",
        );
        assert!(is_cosim_crate(&bench));

        let (_g, helper) = crate_at("[package]\nname = \"helpers\"\n");
        assert!(!is_cosim_crate(&helper));

        let (_g, manifest_only) = crate_at("[workspace]\nmembers = []\n");
        assert!(!is_cosim_crate(&manifest_only));

        // A mixed-signal bench's whole crate is generated from its mist.toml,
        // build.rs included, so it is not this code's business.
        let (_g, mixed) = crate_at(
            "[package]\nname = \"m\"\n[lib]\ncrate-type = [\"cdylib\"]\n",
        );
        std::fs::write(mixed.join("mist.toml"), "").unwrap();
        assert!(!is_cosim_crate(&mixed));
    }

    /// The failure this exists for: a clone or a `git clean -fdx` leaves a
    /// cosim crate with no `build.rs`, and the bench then fails at link time
    /// with an error that says nothing about it.
    #[test]
    fn a_missing_build_script_is_put_back() {
        let (_g, dir) = crate_at("[package]\nname = \"b\"\n");

        assert!(heal(&dir).unwrap());
        assert!(dir.join("build.rs").exists());
        // Already right — nothing rewritten, so cargo's incremental build
        // stays hot.
        assert!(!heal(&dir).unwrap());
    }

    /// A `build.rs` somebody wrote — a bench needing an extra link flag — is
    /// never replaced. Repairing a link error is no reason to throw away work.
    #[test]
    fn a_hand_written_build_script_is_left_alone() {
        let (_g, dir) = crate_at("[package]\nname = \"b\"\n");
        std::fs::write(dir.join("build.rs"), "fn main() { /* mine */ }")
            .unwrap();

        assert!(!heal(&dir).unwrap());
        assert!(std::fs::read_to_string(dir.join("build.rs"))
            .unwrap()
            .contains("mine"));
    }

    /// One written by an older vw is ours to bring up to date.
    #[test]
    fn a_stale_generated_build_script_is_replaced() {
        let (_g, dir) = crate_at("[package]\nname = \"b\"\n");
        std::fs::write(
            dir.join("build.rs"),
            "// Auto-generated by vw — from some earlier version\n",
        )
        .unwrap();

        assert!(heal(&dir).unwrap());
        assert_eq!(
            std::fs::read_to_string(dir.join("build.rs")).unwrap(),
            BUILD_RS,
        );
    }
