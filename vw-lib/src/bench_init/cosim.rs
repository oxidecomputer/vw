/// One handle on the generated `Tb`.
#[derive(Clone, Debug)]
struct Handle {
    /// The Rust field name: `bus_in_go`.
    field: String,
    /// How it reads in a message and a doc comment: `bus_in.go`.
    signal: String,
    /// The `get_child` chain from the top level down: `["bus_in", "go"]`.
    path: Vec<String>,
    /// The subtype it was declared with.
    subtype: String,
    /// Whether the driver owns it.
    driven: bool,
    reach: Reach,
}

/// Which side of an interface the driver is standing on.
///
/// For the design under test the driver is the outside world: it drives the
/// inputs and reads the outputs. For an instance the driver is *implementing*,
/// it is the component: it drives that instance's outputs and reads its
/// inputs. Getting this backwards produces a driver that fights the design
/// on every signal instead of feeding it.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Side {
    /// Outside the entity, looking in.
    Consumer,
    /// Inside it, standing in for what is missing.
    Implementer,
}

impl Side {
    fn drives(self, port: &Interface) -> bool {
        match self {
            Side::Consumer => port.mode().is_driven(),
            Side::Implementer => !port.mode().is_driven(),
        }
    }
}

/// Work out every signal the driver should hold a handle to.
///
/// A record port contributes one handle per element rather than one for
/// itself: the aggregate is not a value, and reading it crashes the GPI
/// layer. Nested records are followed down, to a depth no real design reaches
/// but a self-referential one cannot exceed.
fn plan_handles(
    entity: &EntityInterface,
    side: Side,
    types: &DesignTypes,
) -> Vec<Handle> {
    let mut handles = Vec::new();
    for port in &entity.ports {
        expand(
            side.drives(port),
            &port.name,
            &port.subtype,
            vec![port.name.clone()],
            types,
            0,
            &mut handles,
        );
    }
    handles
}

/// A Rust type name for an instantiation label: `cips_wrapper_inst` becomes
/// `CipsWrapperInst`.
fn struct_name(label: &str) -> String {
    label
        .split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => {
                    first.to_uppercase().collect::<String>()
                        + &chars.as_str().to_lowercase()
                }
                None => String::new(),
            }
        })
        .collect()
}

fn expand(
    driven: bool,
    signal: &str,
    subtype: &str,
    path: Vec<String>,
    types: &DesignTypes,
    depth: usize,
    out: &mut Vec<Handle>,
) {
    // The depth cap is a guard against a source that declares a record
    // reachable from itself, which will not elaborate but should not hang
    // this either.
    if depth < 4 {
        if let Some(fields) = types.record(subtype) {
            for field in fields {
                let mut path = path.clone();
                path.push(field.name.clone());
                expand(
                    driven,
                    &format!("{signal}.{}", field.name),
                    &field.subtype,
                    path,
                    types,
                    depth + 1,
                    out,
                );
            }
            return;
        }
    }

    out.push(Handle {
        field: super::rust_field(&path.join("_")),
        signal: signal.to_string(),
        path,
        subtype: subtype.to_string(),
        driven,
        reach: types.reach(subtype),
    });
}

